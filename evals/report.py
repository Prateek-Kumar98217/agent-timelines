"""Turns docs/eval/runs.jsonl into docs/eval/edit_sensitivity.md."""

import json
import math
import statistics
from collections import defaultdict
from pathlib import Path
from typing import Any

EVAL_DIR = Path(__file__).resolve().parent.parent / "docs" / "eval"
PRICES = Path(__file__).with_name("prices.json")
NOOP_CLASSES = ("noop_user_msg", "noop_tool_result")
FINISHED_WITH_ANSWER = "completed"


def wilson_interval(successes: int, total: int, z: float = 1.96) -> tuple[float, float]:
    """A 95% confidence interval for a proportion that behaves sensibly on small samples."""
    if total == 0:
        return (0.0, 1.0)
    rate = successes / total
    denominator = 1 + z * z / total
    centre = (rate + z * z / (2 * total)) / denominator
    margin = z * math.sqrt(rate * (1 - rate) / total + z * z / (4 * total * total)) / denominator
    return (max(0.0, centre - margin), min(1.0, centre + margin))


def percentile(values: list[float], fraction: float) -> float:
    ordered = sorted(values)
    position = fraction * (len(ordered) - 1)
    lower, upper = math.floor(position), math.ceil(position)
    return ordered[lower] + (ordered[upper] - ordered[lower]) * (position - lower)


def calibrate_threshold(runs: list[dict[str, Any]], fraction: float = 0.1) -> float | None:
    """No-op forks changed nothing, so the threshold sits where most of them count as converged."""
    values = [
        run["final_similarity"]
        for run in runs
        if run["edit_class"] in NOOP_CLASSES and run["final_similarity"] is not None
    ]
    return percentile(values, fraction) if values else None


def summarize_class(runs: list[dict[str, Any]], threshold: float) -> dict[str, Any]:
    scored = [run for run in runs if run["final_similarity"] is not None]
    diverged = sum(1 for run in scored if run["final_similarity"] < threshold)
    with_source = [run for run in runs if run["source_fact_score"] is not None]
    flipped = sum(1 for run in with_source if run["fact_score"] != run["source_fact_score"])
    return {
        "runs": len(runs),
        "completed": sum(1 for run in runs if run["status"] == FINISHED_WITH_ANSWER),
        "scored": len(scored),
        "diverged": diverged,
        "divergence_rate": diverged / len(scored) if scored else None,
        "divergence_ci": wilson_interval(diverged, len(scored)),
        "mean_similarity": statistics.mean(r["final_similarity"] for r in scored)
        if scored
        else None,
        "facts_changed_rate": flipped / len(with_source) if with_source else None,
        "all_facts_rate": sum(1 for run in runs if run["fact_score"] == 1.0) / len(runs),
        "mean_fact_score": statistics.mean(run["fact_score"] for run in runs),
        "mean_tool_overlap": statistics.mean(
            run["tool_call_overlap"] for run in runs if run["tool_call_overlap"] is not None
        )
        if any(run["tool_call_overlap"] is not None for run in runs)
        else None,
    }


def cost_per_branch(runs: list[dict[str, Any]], option: dict[str, Any]) -> float:
    return (
        statistics.mean(
            run["input_tokens"] * option["input_per_million"]
            + run["output_tokens"] * option["output_per_million"]
            for run in runs
        )
        / 1_000_000
    )


def load_runs(path: Path) -> list[dict[str, Any]]:
    with path.open() as file:
        return [json.loads(line) for line in file]


def _percent(value: float | None) -> str:
    return "n/a" if value is None else f"{value * 100:.0f}%"


def render(runs: list[dict[str, Any]], prices: dict[str, Any]) -> str:
    threshold = calibrate_threshold(runs)
    if threshold is None:
        raise ValueError("no no-op forks to calibrate against")
    by_class: dict[str, list[dict[str, Any]]] = defaultdict(list)
    for run in runs:
        by_class[run["edit_class"]].append(run)
    noops = [run for name in NOOP_CLASSES for run in by_class[name]]
    baseline = summarize_class(noops, threshold)

    lines = [
        "# Edit sensitivity",
        "",
        f"{len(runs)} branches from {len({r['task_id'] for r in runs})} tasks with "
        f"{runs[0]['model']}, generated by `evals/report.py`. Small samples: compare intervals, "
        "not single percentages.",
        "",
        f"**Convergence threshold:** similarity of {threshold:.3f}, the 10th percentile of no-op "
        "forks. A branch below it diverged from its source. By construction, about 10% of no-op "
        "forks count as diverged, so that's the floor an edit must clearly beat.",
        "",
        "| Edit | Runs | Completed | Diverged (95% CI) | Mean similarity | Facts changed "
        "| All facts right | Tool overlap |",
        "|---|---|---|---|---|---|---|---|",
    ]

    def row(name: str, summary: dict[str, Any]) -> str:
        low, high = summary["divergence_ci"]
        similarity = summary["mean_similarity"]
        overlap = summary["mean_tool_overlap"]
        return (
            f"| {name} | {summary['runs']} | {summary['completed']} "
            f"| {_percent(summary['divergence_rate'])} ({low * 100:.0f}-{high * 100:.0f}%) "
            f"| {'n/a' if similarity is None else f'{similarity:.3f}'} "
            f"| {_percent(summary['facts_changed_rate'])} "
            f"| {_percent(summary['all_facts_rate'])} "
            f"| {'n/a' if overlap is None else f'{overlap:.2f}'} |"
        )

    lines.append(row("**No-op baseline**", baseline))
    edits = {
        name: summarize_class(items, threshold)
        for name, items in by_class.items()
        if name != "main" and name not in NOOP_CLASSES
    }
    for name, summary in sorted(
        edits.items(), key=lambda item: -(item[1]["divergence_rate"] or 0.0)
    ):
        lines.append(row(name, summary))
    baseline_high = baseline["divergence_ci"][1]
    above = [n for n, s in edits.items() if s["divergence_ci"][0] > baseline_high]
    lines += [
        "",
        "**Clearly above the baseline** (intervals don't overlap): "
        + (", ".join(sorted(above)) if above else "none at this sample size")
        + ".",
    ]

    finished = [run for run in runs if run["status"] == FINISHED_WITH_ANSWER]
    mains = by_class["main"]
    statuses: dict[str, int] = defaultdict(int)
    for run in runs:
        statuses[run["status"]] += 1
    turns = [run["turns"] for run in mains]
    main_success = summarize_class(mains, threshold)["all_facts_rate"]
    priced = finished or runs
    median_in = round(statistics.median(run["input_tokens"] for run in priced))
    median_out = round(statistics.median(run["output_tokens"] for run in priced))
    lines += [
        "",
        "## Reading these results",
        "",
        "- **Similarity follows wording, not facts.** Compare the Diverged and Facts changed "
        "columns: an edit can change the answer's facts while the text stays close enough to count "
        "as converged. Don't read convergence as agreement.",
        "- **`user_paraphrase` and `user_other_task` can't happen in the product.** They edit the "
        "first message through the engine, and the API has since been changed to refuse that, "
        "because a tree's task is fixed. They're kept as a measure of the model's sensitivity.",
        "- **These tasks use the fixed evaluation corpus** through `kb_search`. Real tasks search "
        "pages they fetched themselves, so these results don't measure that path.",
        "- **Times aren't a benchmark.** Other work ran on the same machine during the experiment.",
    ]
    lines += [
        "",
        "## Runs",
        "",
        f"- **Main runs:** {len(mains)}. Turns median {statistics.median(turns):.0f}, range "
        f"{min(turns)} to {max(turns)}. {sum(1 for t in turns if 4 <= t <= 12)} of {len(mains)} "
        "are inside the 4 to 12 target.",
        f"- **Task success (all required facts):** {_percent(main_success)} of main runs.",
        "- **Outcomes across all branches:** "
        + ", ".join(f"{name} {count}" for name, count in sorted(statuses.items()))
        + ".",
        f"- **Median seconds per branch:** {statistics.median(r['seconds'] for r in runs):.0f}, "
        f"**median tokens:** {statistics.median(r['tokens'] for r in runs):.0f}.",
        "",
        "## Equivalent cost per branch",
        "",
        f"Local models have no bill. {prices['note']}",
        "",
        f"Median tokens per completed branch: {median_in} input and {median_out} output.",
        "",
        "| Priced at | Input per million | Output per million | Cost per completed branch |",
        "|---|---|---|---|",
    ]
    for option in prices["options"]:
        cost = cost_per_branch(finished or runs, option)
        lines.append(
            f"| {option['name']} | ${option['input_per_million']:.3f} "
            f"| ${option['output_per_million']:.3f} | ${cost:.5f} |"
        )
    return "\n".join(lines) + "\n"


def main() -> None:
    runs = load_runs(EVAL_DIR / "runs.jsonl")
    prices = json.loads(PRICES.read_text())
    report = render(runs, prices)
    (EVAL_DIR / "edit_sensitivity.md").write_text(report)
    print(report)


if __name__ == "__main__":
    main()
